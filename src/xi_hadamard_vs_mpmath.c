#ifndef M_PI
#define M_PI 3.141592653589793238462643383279502884
#endif

// 50-digit mpmath comparison. Paper Theorem III, Section 8.4.
/* ---- mpmath reference values (50-digit precision, generated externally) ----
 */

static const struct {
  double t;
  double log_xi; /* log|xi(1/2+it)| from mpmath */
} mpmath_refs[] = {
    {14.1347251417, -30.66818121793730}, {21.0220396388, -35.22221987565582},
    {30.4248761259, -41.47041217178927}, {50.0, -33.38750994836327},
    {100.0, -69.37730139844239},         {150.0, -111.32498031241307},
    {200.0, -145.97373400189206},        {300.0, -221.96527692342100},
    {500.0, -387.16287900000000},
};
static const int n_ref = sizeof(mpmath_refs) / sizeof(mpmath_refs[0]);

/* mpmath log10|xi| at zeros (should be ~-54 to -64) */
static const double log10_xi_at_zeros[] = {
    -54.0, -56.0, -56.0, -58.0, -59.0, -60.0, -61.0, -62.0, -63.0, -64.0,
};

/* ---- Hadamard product for xi(1/2+it) ---- */

static double log_xi_hadamard_it(double t, int N) {
  double lr = log(0.5); /* xi(0) = 1/2 */
  int maxN = (N < N_REF) ? N : N_REF;
  for (int k = 0; k < maxN; k++) {
    double g = ZETA_ZEROS[k];
    double num = g * g - t * t;
    double den = 0.25 + g * g;
    lr += log(fabs(num)) - log(den);
  }
  return lr;
}

/* ---- Hadamard tail estimate ---- */

static double hadamard_tail_estimate(double t, int N) {
  double tail = 0.0;
  double t2q = t * t + 0.25;
  /* Use Weyl law approximation for tail */
  int tail_terms = 10000;
  for (int k = N + 1; k <= N + tail_terms; k++) {
    double g = 2.0 * M_PI * k / log((double)k + 1.0);
    tail += -t2q / (g * g);
  }
  /* Analytic tail beyond N+tail_terms: integrate -t2q/g(k)^2 dk
   * g(k) ~ 2pi*k/log(k), so g^2 ~ 4pi^2*k^2/log(k)^2
   * integral of -t2q*log(k)^2/(4pi^2*k^2) dk from N to inf
   * ~ -t2q * log(N)^2 / (4pi^2 * N)
   */
  double k0 = (double)(N + tail_terms);
  double analytic_tail = -t2q * log(k0) * log(k0) / (4.0 * M_PI * M_PI * k0);
  return tail + analytic_tail;
}

/* ====================================================================
 * TEST 1: Hadamard vs mpmath at reference points
 * ==================================================================== */

static void test_hadamard_vs_mpmath(void) {
  printf("====================================================================="
         "\n");
  printf("  TEST 1: Hadamard Product vs mpmath Ground Truth\n");
  printf("  Reference: mpmath.mp.dps=50 (50 decimal digits)\n");
  printf("====================================================================="
         "\n\n");

  int N_vals[] = {500, 1000, 2000};
  int nN = 3;

  printf("  %10s  %20s", "t", "log|xi_mpmath|");
  for (int iN = 0; iN < nN; iN++)
    printf("  |diff| N=%d", N_vals[iN]);
  printf("  |tail diff|\n");
  printf("  %10s  %20s", "---", "---");
  for (int iN = 0; iN < nN; iN++)
    printf("  %14s", "---");
  printf("  %14s\n", "---");

  for (int i = 0; i < n_ref; i++) {
    double t = mpmath_refs[i].t;
    double log_xi_mp = mpmath_refs[i].log_xi;

    printf("  %10.2f  %20.6f", t, log_xi_mp);

    double best_diff = 1e300;
    for (int iN = 0; iN < nN; iN++) {
      int N = N_vals[iN];
      double log_xi_H = log_xi_hadamard_it(t, N);
      double diff = fabs(log_xi_H - log_xi_mp);
      if (diff < best_diff)
        best_diff = diff;
      printf("  %14.6e", diff);
    }

    double tail = hadamard_tail_estimate(t, N_REF);
    double log_xi_H_tail = log_xi_hadamard_it(t, N_REF) + tail;
    double tail_diff = fabs(log_xi_H_tail - log_xi_mp);

    printf("  %14.6e\n", tail_diff);
  }
  printf("\n");
}

/* ====================================================================
 * TEST 2: Convergence analysis at fixed t
 * ==================================================================== */

static void test_convergence(void) {
  printf("====================================================================="
         "\n");
  printf("  TEST 2: Hadamard Convergence to mpmath — Rate Analysis\n");
  printf("====================================================================="
         "\n\n");

  int test_ref[] = {3, 4, 5}; /* t=50, 100, 200 */
  int nt = 3;

  int N_vals[] = {100, 200, 500, 1000, 2000};
  int nN = 5;

  for (int it = 0; it < nt; it++) {
    int idx = test_ref[it];
    double t = mpmath_refs[idx].t;
    double log_xi_mp = mpmath_refs[idx].log_xi;

    printf("  t = %.1f, log|xi_mpmath| = %.6f\n\n", t, log_xi_mp);
    printf("  %4s  %14s  %14s  %14s  %12s\n", "N", "log|xi_H|", "|raw diff|",
           "log|xi_H+tail|", "|tail diff|");
    printf("  %4s  %14s  %14s  %14s  %12s\n", "---", "---", "---", "---",
           "---");

    double prev_diff = 0.0;

    for (int iN = 0; iN < nN; iN++) {
      int N = N_vals[iN];
      double log_xi_H = log_xi_hadamard_it(t, N);
      double tail = hadamard_tail_estimate(t, N);
      double log_xi_H_tail = log_xi_H + tail;

      double raw_diff = fabs(log_xi_H - log_xi_mp);
      double tail_diff = fabs(log_xi_H_tail - log_xi_mp);
      double conv_rate = (prev_diff > 1e-15) ? prev_diff / raw_diff : 0.0;

      printf("  %4d  %14.6f  %14.6e  %14.6f  %12.6e  (%.3fx)\n", N, log_xi_H,
             raw_diff, log_xi_H_tail, tail_diff, conv_rate);

      prev_diff = raw_diff;
    }
    printf("\n");
  }
}

/* ====================================================================
 * TEST 3: Hadamard at zeta zeros — should vanish
 * ==================================================================== */

static void test_at_zeros(void) {
  printf("====================================================================="
         "\n");
  printf("  TEST 3: Hadamard Product at Zeta Zeros\n");
  printf("  xi_H(1/2+i*gamma_k) should approach 0 as N -> inf\n");
  printf("  mpmath reference: |xi| ~ 10^-54 to 10^-64 at zeros\n");
  printf("====================================================================="
         "\n\n");

  printf("  %4s  %14s  %14s  %10s  %14s\n", "k", "gamma_k", "log|xi_H|",
         "log10|xi_H|", "mpmath log10");
  printf("  %4s  %14s  %14s  %10s  %14s\n", "---", "---", "---", "---", "---");

  int nk = 10;
  double log10_e = 1.0 / log(10.0);

  for (int k = 0; k < nk && k < N_REF; k++) {
    double g = ZETA_ZEROS[k];
    double log_xi_H = log_xi_hadamard_it(g, N_REF);
    double log10_xi_H = log_xi_H * log10_e;

    printf("  %4d  %14.4f  %14.6f  %10.2f  %14.0f\n", k, g, log_xi_H,
           log10_xi_H, log10_xi_at_zeros[k]);
  }
  printf("\n");
}

/* ====================================================================
 * TEST 4: Summary — Hadamard vs mpmath across all reference points
 * ==================================================================== */

static void test_summary(void) {
  printf("====================================================================="
         "\n");
  printf("  TEST 4: Summary — Hadamard vs mpmath (N=2000)\n");
  printf("====================================================================="
         "\n\n");

  double max_raw_diff = 0.0, max_tail_diff = 0.0;
  double avg_raw_diff = 0.0, avg_tail_diff = 0.0;

  for (int i = 0; i < n_ref; i++) {
    double t = mpmath_refs[i].t;
    double log_xi_mp = mpmath_refs[i].log_xi;

    double log_xi_H = log_xi_hadamard_it(t, N_REF);
    double raw_diff = fabs(log_xi_H - log_xi_mp);

    double tail = hadamard_tail_estimate(t, N_REF);
    double log_xi_H_tail = log_xi_H + tail;
    double tail_diff = fabs(log_xi_H_tail - log_xi_mp);

    if (raw_diff > max_raw_diff)
      max_raw_diff = raw_diff;
    if (tail_diff > max_tail_diff)
      max_tail_diff = tail_diff;
    avg_raw_diff += raw_diff;
    avg_tail_diff += tail_diff;
  }

  avg_raw_diff /= n_ref;
  avg_tail_diff /= n_ref;

  printf("  N = %d reference points\n\n", n_ref);
  printf("  Raw Hadamard (no tail):\n");
  printf("    Mean |diff|: %.4e\n", avg_raw_diff);
  printf("    Max  |diff|: %.4e\n\n", max_raw_diff);

  printf("  Tail-corrected Hadamard:\n");
  printf("    Mean |diff|: %.4e\n", avg_tail_diff);
  printf("    Max  |diff|: %.4e\n\n", max_tail_diff);

  printf("  At zeta zeros:\n");
  printf("    mpmath |xi|: 10^-54 to 10^-64 (essentially 0)\n");
  printf("    Hadamard at N=2000: see TEST 3\n\n");
}

